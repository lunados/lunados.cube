#!/usr/bin/env python3
"""Write and verify the agent environment lock for an offline wheelhouse.

The lock pins the Linux CPython runtime archive and every wheel by SHA-256.
It is generated on the networked Mac from downloaded files and checked again
inside the offline agent environment before anything is installed."""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

HEADER = '# aiaeao.cube.agent-env-lock/1'
WHEEL = re.compile(r'^(?P<name>[A-Za-z0-9_.]+)-(?P<version>[^-]+)-')

def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()

def normalize(name: str) -> str:
    return re.sub(r'[-_.]+', '-', name).lower()

def write(wheels: Path, archive: Path, target: str, lock: Path) -> None:
    files = sorted(p for p in wheels.glob('*.whl'))
    if not files:
        raise SystemExit('No wheels in ' + str(wheels))
    if not archive.is_file():
        raise SystemExit('Missing runtime archive ' + str(archive))
    lines = [HEADER, '# target: ' + target,
             '# python-archive: ' + archive.name + ' sha256=' + sha256(archive),
             '# Generated by scripts/dev/build_wheelhouse.sh; do not edit by hand.']
    seen = {}
    for wheel in files:
        match = WHEEL.match(wheel.name)
        if not match:
            raise SystemExit('Unrecognised wheel filename ' + wheel.name)
        name = normalize(match['name'])
        if name in seen:
            raise SystemExit('Two wheels for ' + name + ': ' + seen[name] + ', ' + wheel.name)
        seen[name] = wheel.name
        lines.append(f"{name}=={match['version']} --hash=sha256:{sha256(wheel)}")
    lock.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{lock}: runtime + {len(files)} wheels')

def archive_entry(lock: Path) -> tuple[str, str]:
    text = lock.read_text(encoding='utf-8')
    if not text.startswith(HEADER):
        raise SystemExit('Not an agent-env lock: ' + str(lock))
    match = re.search(r'^# python-archive: (\S+) sha256=([0-9a-f]{64})$', text, re.M)
    if not match:
        raise SystemExit('Lock has no runtime archive entry')
    return match[1], match[2]

def verify_archive(lock: Path, directory: Path) -> None:
    name, expected = archive_entry(lock)
    path = directory / name
    if not path.is_file():
        raise SystemExit('Runtime archive missing: ' + str(path))
    if sha256(path) != expected:
        raise SystemExit('Runtime archive hash mismatch: ' + str(path))
    print(path)

def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    w = sub.add_parser('write')
    w.add_argument('--wheels', type=Path, required=True)
    w.add_argument('--archive', type=Path, required=True)
    w.add_argument('--target', required=True)
    w.add_argument('--lock', type=Path, required=True)
    v = sub.add_parser('verify-archive')
    v.add_argument('--lock', type=Path, required=True)
    v.add_argument('--dir', type=Path, required=True)
    opts = parser.parse_args(argv)
    if opts.command == 'write':
        write(opts.wheels, opts.archive, opts.target, opts.lock)
    else:
        verify_archive(opts.lock, opts.dir)
    return 0

if __name__ == '__main__':
    sys.exit(main())
